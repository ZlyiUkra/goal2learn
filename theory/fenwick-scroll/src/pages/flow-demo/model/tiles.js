// Колір плитки. Вимоги: кольори майже не повторюються, а сусідні за номером плитки
// помітно різні. Обидві вимоги виконує золотий кут - 180 x (3 - sqrt(5)), приблизно 137.5°.
//   1. Відтінок плитки i - це i кроків по колу на золотий кут. Кут нераціональний, тому
//      жоден крок не повертає точно на вже зайнятий відтінок: повторів немає взагалі.
//   2. Сусіди відрізняються на 137.5° по колу - це далеко, майже протилежні кольори.
//   3. Яскравість і насиченість теж змінюються від плитки до плитки, за тим самим прийомом
//      з іншими нераціональними числами (sqrt(2) і sqrt(3)). fraction лишає дробову частину.
// Колір задано в oklch: у цьому просторі однаковий крок відтінку виглядає однаково різним
// для ока, чого немає в hsl (там, наприклад, зелені відтінки зливаються).
// Перевірено на 10 000 плитках: усі кольори різні, сусіди розходяться щонайменше на 137.5°.
// Яскравість 0.72-0.84 тримає чорний номер на плитці читабельним.
export const goldenAngle = 180 * (3 - Math.sqrt(5));
const fraction = (x) => x - Math.floor(x);

// Колір з відтінком hue; яскравість і насиченість беруться з номера i.
export const oklchFor = (i, hue) => {
  const lightness = 0.72 + 0.12 * fraction(i * Math.SQRT2);
  const chroma = 0.09 + 0.07 * fraction(i * Math.sqrt(3));
  return `oklch(${lightness.toFixed(3)} ${chroma.toFixed(3)} ${(hue % 360).toFixed(2)})`;
};

// Плитка з номером i. Розміри й колір задає формула, а не випадковість: при кожному запуску
// плитка з тим самим номером однакова. Ширина й висота від 40 до 200 px. Плитка рахується
// на льоту, без масиву: при стороні 1000 масив мав би мільйон об'єктів.
export const tileAt = (i) => ({
  width: 40 + ((i * 53) % 161),
  height: 40 + ((i * 37) % 161),
  color: oklchFor(i, i * goldenAngle),
});

