// Сумарна площа count плиток разом із відступами. З неї рахується ширина мозаїки в режимі
// "Скомбіновано": мозаїка площею area з пропорціями вікна width : height має ширину
// sqrt(area * width / height). Справжня мозаїка трохи вища, бо між плитками лишаються дірки.
export const tilesAreaFor = (count) => {
  let sum = 0;
  for (let i = 0; i < count; i += 1) {
    const { width, height } = tileAt(i);
    sum += (width + demo.gap * 2) * (height + demo.gap * 2);
  }
  return sum;
};

// Ширина мозаїки для режиму: стала для "Мозаїка 3000 px", з пропорцій вікна для "Скомбіновано",
// undefined для лінійок (там довжина лінійки дорівнює ширині вікна).
export const mosaicWidthFor = (mode, frame, area) => {
  if (mode === 'fixed') return demo.mosaicWidth;
  if (mode === 'combined') return Math.round(Math.sqrt((area * frame.width) / frame.height));
  return undefined;
};
